func TestFetch(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/list" {
			http.NotFound(w, r)
			return
		}
		if _, err := w.Write([]byte("go,rust,python")); err != nil {
			t.Errorf("failed to write response: %v", err)
		}
	}))
	defer server.Close()

	originalAPI := API
	API = server.URL
	defer func() { API = originalAPI }()

	items, err := Fetch()
	if err != nil {
		t.Fatalf("Fetch() error = %v", err)
	}
	if !reflect.DeepEqual(items, []string{"go", "rust", "python"}) {
		t.Errorf("Fetch() = %q, want [go rust python]", items)
	}
}

func TestFetchNonOKStatus(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		http.Error(w, "server error", http.StatusInternalServerError)
	}))
	defer server.Close()

	originalAPI := API
	API = server.URL
	defer func() { API = originalAPI }()

	items, err := Fetch()
	if err == nil {
		t.Fatal("Fetch() expected error for non-200 status, got nil")
	}
	if !strings.Contains(err.Error(), "unexpected status") {
		t.Errorf("Fetch() error = %v, want it to mention unexpected status", err)
	}
	if items != nil {
		t.Errorf("Fetch() items = %q, want nil on error", items)
	}
}

