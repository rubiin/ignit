func TestParse(t *testing.T) {
	tests := []struct {
		name string
		body string
		want []string
	}{
		{
			name: "simple list",
			body: "go,rust,python",
			want: []string{"go", "rust", "python"},
		},
		{
			name: "trims whitespace",
			body: " go , rust ,python\n",
			want: []string{"go", "rust", "python"},
		},
		{
			name: "drops empty entries",
			body: "go,,rust,",
			want: []string{"go", "rust"},
		},
		{
			name: "empty body yields nil",
			body: "",
			want: nil,
		},
		{
			name: "whitespace-only body yields nil",
			body: " , , ",
			want: nil,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := Parse(tt.body)
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("Parse(%q) = %q, want %q", tt.body, got, tt.want)
			}
		})
	}
}

func TestRender(t *testing.T) {
	got := Render([]string{"go", "rust"})

	want := `package envs

// Code generated by ` + "`ignit --update-list`" + `. DO NOT EDIT.
// Source: https://www.toptal.com/developers/gitignore/api/list

// List is a static snapshot of the template list from
// https://github.com/toptal/gitignore.io. The picker works fully
// offline; only writing the .gitignore hits the API.
var List = []string{
	"go",
	"rust",
}
`
	if got != want {
		t.Errorf("Render output mismatch:\ngot:\n%s\nwant:\n%s", got, want)
	}
}

func TestRenderQuotesSpecialCharacters(t *testing.T) {
	got := Render([]string{"c++", `back` + "`" + `tick`, "quote\"d"})

	// %q must produce valid Go string literals for tricky names.
	for _, literal := range []string{`"c++"`, "\"back`tick\"", `"quote\"d"`} {
		if !strings.Contains(got, "\t"+literal+",\n") {
			t.Errorf("Render output missing %s literal:\n%s", literal, got)
		}
	}
}

func TestRenderOutputParsesAsGo(t *testing.T) {
	src := Render([]string{"go", "c++", "odd\"name"})

	fset := token.NewFileSet()
	if _, err := parser.ParseFile(fset, "environments.go", src, 0); err != nil {
		t.Fatalf("rendered output does not parse as Go: %v", err)
	}
}

func TestWrite(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "environments.go")

	content := Render([]string{"go", "rust"})
	if err := Write(path, content); err != nil {
		t.Fatalf("Write() error = %v", err)
	}

	written, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("failed to read written file: %v", err)
	}
	if string(written) != content {
		t.Errorf("written content mismatch:\ngot:\n%s\nwant:\n%s", written, content)
	}
}

