func TestFetchEnvironmentList(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/list" {
			http.NotFound(w, r)
			return
		}
		w.Write([]byte("go,rust,python"))
	}))
	defer server.Close()

	originalAPI := gitignoreAPI
	gitignoreAPI = server.URL
	defer func() { gitignoreAPI = originalAPI }()

	items, err := fetchEnvironmentList()
	if err != nil {
		t.Fatalf("fetchEnvironmentList() error = %v", err)
	}
	if !reflect.DeepEqual(items, []string{"go", "rust", "python"}) {
		t.Errorf("fetchEnvironmentList() = %q, want [go rust python]", items)
	}
}

func TestFetchEnvironmentListNonOKStatus(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		http.Error(w, "server error", http.StatusInternalServerError)
	}))
	defer server.Close()

	originalAPI := gitignoreAPI
	gitignoreAPI = server.URL
	defer func() { gitignoreAPI = originalAPI }()

	items, err := fetchEnvironmentList()
	if err == nil {
		t.Fatal("fetchEnvironmentList() expected error for non-200 status, got nil")
	}
	if !strings.Contains(err.Error(), "unexpected status") {
		t.Errorf("fetchEnvironmentList() error = %v, want it to mention unexpected status", err)
	}
	if items != nil {
		t.Errorf("fetchEnvironmentList() items = %q, want nil on error", items)
	}
}

