func TestParseEnvironmentList(t *testing.T) {
	tests := []struct {
		name string
		body string
		want []string
	}{
		{
			name: "simple list",
			body: "go,rust,python",
			want: []string{"go", "rust", "python"},
		},
		{
			name: "trims whitespace",
			body: " go , rust ,python\n",
			want: []string{"go", "rust", "python"},
		},
		{
			name: "drops empty entries",
			body: "go,,rust,",
			want: []string{"go", "rust"},
		},
		{
			name: "empty body yields nil",
			body: "",
			want: nil,
		},
		{
			name: "whitespace-only body yields nil",
			body: " , , ",
			want: nil,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := parseEnvironmentList(tt.body)
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("parseEnvironmentList(%q) = %q, want %q", tt.body, got, tt.want)
			}
		})
	}
}

func TestRenderEnvironmentList(t *testing.T) {
	got := renderEnvironmentList([]string{"go", "rust"})

	want := `package main

// Code generated by ` + "`ignit -update-list`" + `. DO NOT EDIT.
// Source: https://www.toptal.com/developers/gitignore/api/list

// environments is a static snapshot of the template list from
// https://github.com/toptal/gitignore.io. The picker works fully
// offline; only writing the .gitignore hits the API.
var environments = []string{
	"go",
	"rust",
}
`
	if got != want {
		t.Errorf("renderEnvironmentList output mismatch:\ngot:\n%s\nwant:\n%s", got, want)
	}
}

func TestRenderEnvironmentListQuotesSpecialCharacters(t *testing.T) {
	got := renderEnvironmentList([]string{"c++", `back` + "`" + `tick`, "quote\"d"})

	// %q must produce valid Go string literals for tricky names.
	for _, literal := range []string{`"c++"`, "\"back`tick\"", `"quote\"d"`} {
		if !strings.Contains(got, "\t"+literal+",\n") {
			t.Errorf("renderEnvironmentList output missing %s literal:\n%s", literal, got)
		}
	}
}

func TestRenderEnvironmentListOutputParsesAsGo(t *testing.T) {
	src := renderEnvironmentList([]string{"go", "c++", "odd\"name"})

	fset := token.NewFileSet()
	if _, err := parser.ParseFile(fset, "environments.go", src, 0); err != nil {
		t.Fatalf("rendered output does not parse as Go: %v", err)
	}
}

func TestWriteEnvironmentList(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "environments.go")

	content := renderEnvironmentList([]string{"go", "rust"})
	if err := writeEnvironmentList(path, content); err != nil {
		t.Fatalf("writeEnvironmentList() error = %v", err)
	}

	written, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("failed to read written file: %v", err)
	}
	if string(written) != content {
		t.Errorf("written content mismatch:\ngot:\n%s\nwant:\n%s", written, content)
	}
}

